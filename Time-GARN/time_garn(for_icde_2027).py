# 2. Time-GARN | Custom Recurrent Cell Definition
# ==============================================================================
class CustomRecurrentCell(nn.Module):
    def __init__(self, input_size: int, hidden_size: int, external_var_size: int):
        super(CustomRecurrentCell, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        self.external_var_size = external_var_size

        # --- Parameters for Input Gate ---
        self.linear_x_to_it = nn.Linear(self.input_size, self.hidden_size)
        self.linear_h_to_it = nn.Linear(self.hidden_size, self.hidden_size)

        # --- Parameters for Ratio Gate ---
        self.linear_it_to_rt_numerator = nn.Linear(self.hidden_size, self.hidden_size)
        self.linear_ex_to_rt_denominator = nn.Linear(self.external_var_size, self.hidden_size)
        self.epsilon = 1e-8 # Small value for numerical stability in division

        # --- Parameters for Attention Gate ---
        self.query_transform = nn.Linear(self.hidden_size, self.hidden_size)
        self.key_transform = nn.Linear(self.external_var_size, self.hidden_size)
        self.value_transform = nn.Linear(self.external_var_size, self.hidden_size)

        # For scaled dot-product attention
        self.scale_factor = torch.sqrt(torch.tensor(self.hidden_size, dtype=torch.float32))

    def forward(self, x_t: torch.Tensor, h_prev: torch.Tensor, ex_t: torch.Tensor):
        # 1. Input Gate (It)
        it_output = torch.sigmoid(self.linear_x_to_it(x_t) + self.linear_h_to_it(h_prev))

        # 2. Ratio Gate (Rt)
        it_transformed = self.linear_it_to_rt_numerator(it_output)
        ex_transformed_for_ratio = self.linear_ex_to_rt_denominator(ex_t)

        numerator = it_transformed
        denominator = ex_transformed_for_ratio

        ratio_term = numerator / (denominator + self.epsilon)
        rt_output = torch.sigmoid(ratio_term)

        # 3. Attention Gate
        Q = self.query_transform(rt_output)
        K = self.key_transform(ex_t)
        V = self.value_transform(ex_t)

        # Scaled dot-product attention
        scores = torch.sum(Q * K, dim=1, keepdim=True) / self.scale_factor
        attention_weights = torch.softmax(scores, dim=1)

        best_ratio = attention_weights * V

        # 4. Final Output (New H_t)
        h_curr = best_ratio * self.value_transform(ex_t)

        return h_curr

