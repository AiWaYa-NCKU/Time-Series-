# 6. Metric Calculation Functions
# ==============================================================================
def calculate_metrics(y_true, y_pred, epsilon=1e-8):
    y_true_flat = y_true.flatten()
    y_pred_flat = y_pred.flatten()

    mse = mean_squared_error(y_true_flat, y_pred_flat)
    mae = mean_absolute_error(y_true_flat, y_pred_flat)

    sum_squared_error = np.sum((y_true_flat - y_pred_flat)**2)
    sum_squared_total = np.sum((y_true_flat - np.mean(y_true_flat))**2)
    rse = np.sqrt(sum_squared_error / (sum_squared_total + epsilon))

    mape = np.mean(np.abs((y_true_flat - y_pred_flat) / (y_true_flat + epsilon))) * 100

    corr_coeff, _ = pearsonr(y_true_flat, y_pred_flat)
    if np.isnan(corr_coeff):
        corr_coeff = 0.0

    return {
        'MSE': mse,
        'MAE': mae,
        'RSE': rse,
        'MAPE': mape,
        'CORR': corr_coeff
    }

