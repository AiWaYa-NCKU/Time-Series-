# 5. Feature Selection Function
# ==============================================================================
def select_external_features(df, target_col, all_features_except_target, method='pearson', num_features=1):
    if not isinstance(target_col, list):
        target_col_name = target_col
    else:
        target_col_name = target_col[0]
        print(f"Warning: Multiple target columns provided. Using '{target_col_name}' for feature selection.")

    candidate_df = df[all_features_except_target]
    target_series = df[target_col_name]

    if method == 'pearson':
        print(f"Selecting {num_features} external features using Pearson Correlation...")
        correlations = {}
        for feature in candidate_df.columns:
            corr, _ = pearsonr(candidate_df[feature], target_series)
            correlations[feature] = abs(corr)

        sorted_features = sorted(correlations.items(), key=lambda item: item[1], reverse=True)
        selected_features = [feature for feature, corr in sorted_features[:num_features]]
        print(f"Top {num_features} Pearson-correlated features: {selected_features}")
        return selected_features
    else:
        raise ValueError(f"Unknown feature selection method: {method}. Supported methods: ['pearson']")

