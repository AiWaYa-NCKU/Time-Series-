def select_external_features(df, target_col, all_features_except_target, method='pearson', num_features=1):
    """
    Selects external features based on the specified method.

    Args:
        df (pd.DataFrame): The full DataFrame including target and all candidate features.
        target_col (str or list): The name(s) of the target column(s).
        all_features_except_target (list): List of all candidate feature column names.
        method (str): 'pearson' (for Pearson Correlation).
        num_features (int): The number of top features to select.

    Returns:
        list: A list of selected external feature column names.
    """
    if not isinstance(target_col, list):
        target_col_name = target_col
    else: # If multiple targets, pick the first one for correlation for simplicity
        target_col_name = target_col[0]
        print(f"Warning: Multiple target columns provided. Using '{target_col_name}' for feature selection.")


    candidate_df = df[all_features_except_target]
    target_series = df[target_col_name]

    if method == 'pearson':
        print(f"Selecting {num_features} external features using Pearson Correlation...")
        correlations = {}
        for feature in candidate_df.columns:
            # Calculate absolute Pearson correlation coefficient
            corr, _ = pearsonr(candidate_df[feature], target_series)
            correlations[feature] = abs(corr)

        # Sort features by absolute correlation in descending order
        sorted_features = sorted(correlations.items(), key=lambda item: item[1], reverse=True)
        selected_features = [feature for feature, corr in sorted_features[:num_features]]
        print(f"Top {num_features} Pearson-correlated features: {selected_features}")
        return selected_features
    elif method == 'granger':
        print("Granger Causality is a more complex method and requires statistical tests (e.g., using statsmodels).")
        print("It often involves checking for stationarity and interpreting p-values, which is beyond this automated selection.")
        print("For a full implementation, typically iterate through features and perform:")
        print("  from statsmodels.tsa.stattools import grangercausalitytests")
        print("  test_result = grangercausalitytests(df[[feature, target_col_name]], maxlag=[lag_value], verbose=False)")
        print("Consider manual selection or a dedicated library for robust Granger causality feature selection.")
        print(f"Returning the first {num_features} features from candidates as a placeholder.")
        return all_features_except_target[:num_features]
    else:
        raise ValueError(f"Unknown feature selection method: {method}. Supported methods: ['pearson']")


