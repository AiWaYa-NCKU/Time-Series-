# 3. Custom RNN Model for Prediction
# ==============================================================================
class CustomRNNForPrediction(nn.Module):
    def __init__(self, input_size, hidden_size, external_var_size,
                 output_dim, pred_len):
        super().__init__()
        self.hidden_size = hidden_size
        self.pred_len = pred_len
        self.output_dim = output_dim

        self.cell = CustomRecurrentCell(input_size, hidden_size, external_var_size)

        # Output layer to map the final hidden state to the desired prediction length and dimensions
        self.prediction_layer = nn.Linear(self.hidden_size, self.pred_len * self.output_dim)

    def forward(self, inputs, external_vars, initial_h=None):
        # inputs: (batch_size, seq_len, input_size)
        # external_vars: (batch_size, seq_len, external_var_size)

        batch_size, seq_len, _ = inputs.size()

        if initial_h is None:
            initial_h = torch.zeros(batch_size, self.hidden_size, device=inputs.device)

        h_curr = initial_h

        # Process the input sequence using the custom cell
        for t in range(seq_len):
            x_t = inputs[:, t, :]
            ex_t = external_vars[:, t, :]
            h_curr = self.cell(x_t, h_curr, ex_t)

        # Use the final hidden state to make predictions for the entire prediction horizon
        predictions = self.prediction_layer(h_curr) # (batch_size, pred_len * output_dim)
        predictions = predictions.view(batch_size, self.pred_len, self.output_dim) # Reshape

        return predictions

