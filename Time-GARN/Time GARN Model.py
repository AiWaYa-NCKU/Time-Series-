class ETTDataset(Dataset):
    def __init__(self, df, seq_len, pred_len, features_col, external_col, target_col):
        self.seq_len = seq_len
        self.pred_len = pred_len
        self.features_col = features_col
        self.external_col = external_col
        self.target_col = target_col

        # Convert dataframe to numpy array for easier slicing
        self.data = df[features_col].values
        self.external_data = df[external_col].values if isinstance(external_col, list) else df[[external_col]].values
        self.target_data = df[target_col].values if isinstance(target_col, list) else df[[target_col]].values

        self.num_samples = len(self.data) - self.seq_len - self.pred_len + 1

    def __len__(self):
        return self.num_samples

    def __getitem__(self, idx):
        input_seq = self.data[idx : idx + self.seq_len]
        external_seq_input = self.external_data[idx : idx + self.seq_len]
        target_seq = self.target_data[idx + self.seq_len : idx + self.seq_len + self.pred_len]

        return (
            torch.tensor(input_seq, dtype=torch.float32),
            torch.tensor(external_seq_input, dtype=torch.float32),
            torch.tensor(target_seq, dtype=torch.float32)
        )

