# 7. Metric Calculation Functions
# ==============================================================================
def calculate_metrics(y_true, y_pred, epsilon=1e-8):
    """
    Calculates various time series prediction metrics.

    Args:
        y_true (np.array): Ground truth values (original scale). Shape: (N_samples, pred_len, output_dim)
        y_pred (np.array): Predicted values (original scale). Shape: (N_samples, pred_len, output_dim)
        epsilon (float): Small value for numerical stability (e.g., in MAPE denominator).

    Returns:
        dict: A dictionary containing MSE, MAE, RSE, MAPE, and CORR.
    """
    # Flatten the arrays to compute metrics across all points/dimensions
    y_true_flat = y_true.flatten()
    y_pred_flat = y_pred.flatten()

    # MSE (Mean Squared Error)
    mse = mean_squared_error(y_true_flat, y_pred_flat)

    # MAE (Mean Absolute Error)
    mae = mean_absolute_error(y_true_flat, y_pred_flat)

    # RSE (Relative Squared Error)
    sum_squared_error = np.sum((y_true_flat - y_pred_flat)**2)
    sum_squared_total = np.sum((y_true_flat - np.mean(y_true_flat))**2)

    rse = np.sqrt(sum_squared_error / (sum_squared_total + epsilon))

    # MAPE (Mean Absolute Percentage Error)
    mape = np.mean(np.abs((y_true_flat - y_pred_flat) / (y_true_flat + epsilon))) * 100

    # CORR (Pearson Correlation Coefficient)
    corr_coeff, _ = pearsonr(y_true_flat, y_pred_flat)
    if np.isnan(corr_coeff): # Handle cases where std dev is zero
        corr_coeff = 0.0

    return {
        'MSE': mse,
        'MAE': mae,
        'RSE': rse,
        'MAPE': mape,
        'CORR': corr_coeff
    }


