    if loaded_model:
        def predict_time_series(input_csv_file):
            """
            Predicts future time series values using the trained model from a CSV input.

            Args:
                input_csv_file (str): Path to a CSV file containing the last SEQUENCE_LENGTH
                                      data points, with columns matching the training data.

            Returns:
                pd.DataFrame: A DataFrame with the predicted values and metadata.
            """
            if input_csv_file is None:
                return "Please upload a CSV file."

            try:
                input_df = pd.read_csv(input_csv_file.name, parse_dates=['date'] if 'date' in pd.read_csv(input_csv_file.name).columns else False)
                print(f"Loaded input CSV with {len(input_df)} rows.")

                if len(input_df) < SEQUENCE_LENGTH:
                    return f"Error: Input CSV must contain at least {SEQUENCE_LENGTH} rows for prediction. Found {len(input_df)} rows."

                # Select the last SEQUENCE_LENGTH rows for prediction
                prediction_input_df = input_df.tail(SEQUENCE_LENGTH).copy()

                # Ensure columns are in the correct order as during training
                try:
                    input_x_data = prediction_input_df[all_features_for_Xt_input].values
                    input_ex_data = prediction_input_df[external_features].values
                except KeyError as k_err:
                    return f"Error: Missing expected column in input CSV: {k_err}. Ensure columns match training data ({all_features_for_Xt_input} and {external_features})."

                # Scale inputs using the loaded scalers
                input_x_scaled = loaded_scaler_x.transform(input_x_data)
                input_ex_scaled = loaded_scaler_ex.transform(input_ex_data)

                # Convert to torch tensors and add batch dimension
                input_x_tensor = torch.tensor(input_x_scaled, dtype=torch.float32).unsqueeze(0).to(device)
                input_ex_tensor = torch.tensor(input_ex_scaled, dtype=torch.float32).unsqueeze(0).to(device)

                # Make prediction
                with torch.no_grad():
                    predictions_scaled = loaded_model(input_x_tensor, input_ex_tensor)
                predictions_scaled = predictions_scaled.cpu().numpy() # Move to CPU and convert to numpy

                # Inverse transform predictions
                predictions_original_scale = loaded_scaler_target.inverse_transform(
                    predictions_scaled.reshape(-1, OUTPUT_DIM)
                ).reshape(predictions_scaled.shape)

                # Create output DataFrame
                prediction_df = pd.DataFrame({
                    'Time Step (Relative)': np.arange(1, PREDICTION_LENGTH + 1),
                    f'Predicted {target_feature_list[0]}': predictions_original_scale[0, :, 0] # Assuming single target
                })
                return prediction_df

            except Exception as e:
                return f"An error occurred during prediction: {e}. Please check your CSV format and data."

